"""The fixed conversation both benchmark paths replay.

Same human messages, same canned agent responses, fed to two different
context-management strategies (see run_benchmark.py). Keeping the scenario
here and not inline means both paths provably see identical input -- the
only thing that can differ between them is *how much of it, and what,*
each one puts in front of the model.

Realistic-length responses on purpose: a one-line canned reply would make
every prompt trivially small and hide the effect being measured.
"""

